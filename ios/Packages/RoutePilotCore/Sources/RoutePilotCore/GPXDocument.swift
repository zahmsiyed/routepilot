import Foundation
#if canImport(FoundationXML)
import FoundationXML
#endif

public enum GPXFormat: String, CaseIterable, Codable, Sendable {
    case track, route, xcode
    public var title: String {
        switch self {
        case .track: return "Timed track"
        case .route: return "Planned route"
        case .xcode: return "Xcode waypoints"
        }
    }
}

public enum GPXDocument {
    public static let maximumBytes = 4_000_000

    public static func export(route: RouteGeometry, format: GPXFormat, name rawName: String, startTime: Date = Date(), speedKPH: Double = 10, mode: MovementMode = .running) throws -> Data {
        let name = rawName.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
        guard (1...100).contains(name.count), name.unicodeScalars.allSatisfy({ $0.value >= 32 && $0.value != 0xFFFE && $0.value != 0xFFFF }) else {
            throw RoutePilotError("Enter a name of 1–100 printable characters.")
        }
        let timed = format != .route
        if format == .track && (mode == .stationary || route.totalDistance < 0.01) {
            throw RoutePilotError("A timed activity needs a moving route with two distinct points.")
        }
        var startMicroseconds: Int64 = 0
        var samples: [(microseconds: Int64, point: RoutePoint)] = []
        if timed {
            guard speedKPH.isFinite, (0.1...250).contains(speedKPH) else { throw RoutePilotError("Enter a speed between 0.1 and 250 km/h.") }
            let duration = route.totalDistance / (speedKPH / 3.6)
            guard duration <= 365 * 86_400 else { throw RoutePilotError("This GPX would run longer than a year. Use a shorter route or higher speed.") }
            var calendar = Calendar(identifier: .gregorian)
            calendar.timeZone = TimeZone(secondsFromGMT: 0)!
            let epoch = Date(timeIntervalSince1970: 0)
            let upperStart = calendar.date(from: DateComponents(year: 9999, month: 1, day: 1))!
            let upperFinish = calendar.date(from: DateComponents(year: 10000, month: 1, day: 1))!
            guard startTime.timeIntervalSince1970.isFinite, startTime >= epoch, startTime < upperStart else {
                throw RoutePilotError("Choose a start date between 1970 and 9998.")
            }
            guard startTime.addingTimeInterval(duration) < upperFinish else { throw RoutePilotError("The finish time is outside the supported date range.") }
            startMicroseconds = Int64((startTime.timeIntervalSince1970 * 1_000_000).rounded())
            let budget = min(20_000, RouteGeometry.maximumPoints - route.points.count)
            let interval = max(1, duration / Double(budget + 1))
            let extras = min(budget, Int(floor(duration / interval)))
            var byTime: [Int64: RoutePoint] = [:]
            if extras > 0 {
                for index in 1...extras {
                    let seconds = Double(index) * interval
                    if seconds < duration { byTime[Int64((seconds * 1_000_000).rounded())] = route.position(atDistance: seconds * speedKPH / 3.6) }
                }
            }
            for (meters, point) in zip(route.cumulative, route.points) {
                byTime[Int64((meters / (speedKPH / 3.6) * 1_000_000).rounded())] = point
            }
            samples = byTime.sorted(by: { $0.key < $1.key }).map { ($0.key, $0.value) }
        } else { samples = route.points.map { (0, $0) } }

        let description = timed ? "Simulated track generated by RoutePilot; not a recorded workout." : "Planned route created with RoutePilot; no recorded activity or timestamps."
        var xml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<gpx version=\"1.1\" creator=\"RoutePilot\" xmlns=\"http://www.topografix.com/GPX/1/1\"><metadata><name>\(escape(name))</name><desc>\(description)</desc>"
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.calendar = Calendar(identifier: .gregorian)
        formatter.timeZone = TimeZone(secondsFromGMT: 0)
        formatter.dateFormat = "yyyy-MM-dd'T'HH:mm:ss"
        func timestamp(_ microseconds: Int64) -> String {
            let seconds = microseconds / 1_000_000
            let fraction = microseconds % 1_000_000
            return formatter.string(from: Date(timeIntervalSince1970: Double(seconds))) + String(format: ".%06lldZ", fraction)
        }
        if timed { xml += "<time>\(timestamp(startMicroseconds))</time>" }
        xml += "</metadata>"
        let pointTag: String
        switch format {
        case .track:
            xml += "<trk><name>\(escape(name))</name><desc>\(description)</desc><type>\(mode.rawValue)</type><trkseg>"
            pointTag = "trkpt"
        case .route:
            xml += "<rte><name>\(escape(name))</name><type>\(mode.rawValue)</type>"
            pointTag = "rtept"
        case .xcode: pointTag = "wpt"
        }
        for sample in samples {
            xml += "<\(pointTag) lat=\"\(String(format: "%.8f", locale: Locale(identifier: "en_US_POSIX"), sample.point.latitude))\" lon=\"\(String(format: "%.8f", locale: Locale(identifier: "en_US_POSIX"), sample.point.longitude))\">"
            if timed { xml += "<time>\(timestamp(startMicroseconds + sample.microseconds))</time>" }
            xml += "</\(pointTag)>"
        }
        if format == .track { xml += "</trkseg></trk>" }
        if format == .route { xml += "</rte>" }
        xml += "</gpx>"
        return Data(xml.utf8)
    }

    public static func importPoints(_ data: Data) throws -> [RoutePoint] {
        guard !data.isEmpty, data.count <= maximumBytes else { throw RoutePilotError("Choose a GPX file smaller than 4 MB.") }
        guard let text = String(data: data, encoding: .utf8), !text.localizedCaseInsensitiveContains("<!DOCTYPE"), !text.localizedCaseInsensitiveContains("<!ENTITY") else {
            throw RoutePilotError("Choose a UTF-8 GPX document without XML entities or a document type.")
        }
        let delegate = GPXParserDelegate()
        let parser = XMLParser(data: data)
        parser.shouldResolveExternalEntities = false
        parser.delegate = delegate
        guard parser.parse(), delegate.error == nil, delegate.rootIsGPX else {
            throw delegate.error ?? RoutePilotError("That GPX file is malformed or contains unsafe XML.")
        }
        let segments = delegate.segments.filter { !$0.isEmpty }
        guard segments.count <= 1, !segments.isEmpty || delegate.routes.count <= 1 else {
            throw RoutePilotError("Import one continuous track segment or route at a time.")
        }
        return try RouteGeometry(points: segments.first ?? delegate.routes.first ?? delegate.waypoints).points
    }

    public static func importCheckpoints(_ data: Data, maxCheckpoints: Int = 24) throws -> [RoutePoint] {
        guard (1...24).contains(maxCheckpoints) else { throw RoutePilotError("Choose between 1 and 24 checkpoints.") }
        let points = try importPoints(data)
        let count = min(maxCheckpoints, points.count)
        if count == 1 { return [points[0]] }
        return (0..<count).map { points[Int((Double($0) * Double(points.count - 1) / Double(count - 1)).rounded())] }
    }

    public static func filename(_ name: String) -> String {
        let allowed = CharacterSet.alphanumerics.union(CharacterSet(charactersIn: "_-"))
        var result = ""
        var separator = false
        for scalar in name.unicodeScalars {
            if allowed.contains(scalar) {
                if separator && !result.isEmpty { result += "-" }
                result.unicodeScalars.append(scalar)
                separator = false
            } else { separator = true }
        }
        return (result.isEmpty ? "routepilot" : String(result.prefix(80))) + ".gpx"
    }

    private static func escape(_ value: String) -> String {
        value.replacingOccurrences(of: "&", with: "&amp;").replacingOccurrences(of: "<", with: "&lt;").replacingOccurrences(of: ">", with: "&gt;").replacingOccurrences(of: "\"", with: "&quot;").replacingOccurrences(of: "'", with: "&apos;")
    }
}

private final class GPXParserDelegate: NSObject, XMLParserDelegate {
    var error: RoutePilotError?
    var rootIsGPX = false
    var segments: [[RoutePoint]] = []
    var routes: [[RoutePoint]] = []
    var waypoints: [RoutePoint] = []
    private var stack: [String] = []
    private var pointCounts: [String: Int] = [:]

    func parser(_ parser: XMLParser, didStartElement elementName: String, namespaceURI: String?, qualifiedName qName: String?, attributes: [String: String] = [:]) {
        let tag = elementName.split(separator: ":").last.map(String.init) ?? elementName
        let parent = stack.last
        stack.append(tag)
        if stack.count == 1 { rootIsGPX = tag == "gpx" }
        guard rootIsGPX else { fail(parser, "Choose a GPX document."); return }
        guard stack.count <= 64 else { fail(parser, "The GPX structure is too deeply nested."); return }
        if tag == "trkseg" { segments.append([]) }
        if tag == "rte" { routes.append([]) }
        guard ["trkpt", "rtept", "wpt"].contains(tag) else { return }
        guard let lat = attributes["lat"].flatMap(Double.init), let lon = attributes["lon"].flatMap(Double.init) else {
            fail(parser, "Every GPX point needs numeric latitude and longitude."); return
        }
        let point = RoutePoint(latitude: lat, longitude: lon)
        guard point.isValid else { fail(parser, "The GPX file contains an invalid latitude or longitude."); return }
        // Older RoutePilot files contain both Xcode waypoints and the same
        // track. Bound each representation, then prefer the track below.
        pointCounts[tag, default: 0] += 1
        guard pointCounts[tag, default: 0] <= RouteGeometry.maximumPoints else { fail(parser, "Choose a GPX file with at most 30,000 points per track, route, or waypoint list."); return }
        if tag == "trkpt", parent == "trkseg", !segments.isEmpty { segments[segments.count - 1].append(point) }
        if tag == "rtept", parent == "rte", !routes.isEmpty { routes[routes.count - 1].append(point) }
        if tag == "wpt", parent == "gpx" { waypoints.append(point) }
    }
    func parser(_ parser: XMLParser, didEndElement elementName: String, namespaceURI: String?, qualifiedName qName: String?) { if !stack.isEmpty { stack.removeLast() } }
    func parser(_ parser: XMLParser, foundInternalEntityDeclarationWithName name: String, value: String?) { fail(parser, "XML entities are not allowed in GPX files.") }
    func parser(_ parser: XMLParser, foundExternalEntityDeclarationWithName name: String, publicID: String?, systemID: String?) { fail(parser, "External XML entities are not allowed.") }
    func parser(_ parser: XMLParser, resolveExternalEntityName name: String, systemID: String?) -> Data? { fail(parser, "External XML entities are not allowed."); return nil }
    private func fail(_ parser: XMLParser, _ message: String) { error = RoutePilotError(message); parser.abortParsing() }
}
